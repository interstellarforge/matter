/**
 * Payload (3.90-3.92) uses `html[data-theme="light|dark"]` for its colour mode and declares its
 * defaults in `@layer payload-default, payload`. Matter uses `data-theme` for the product theme
 * (deep-space | professional | pulsar) and `data-color-mode` for light/dark. Inside Payload the roles swap:
 * Payload's `data-theme` drives the colour mode and the Matter product theme moves to
 * `data-matter-theme`.
 */
export function remapAttributes(css: string): string {
  return css
    .replaceAll("[data-theme", "[data-matter-theme")
    .replaceAll("[data-color-mode", "[data-theme");
}

const steps = (from: number, to: number, by: number) =>
  Array.from({ length: (to - from) / by + 1 }, (_, i) => from + i * by);

/**
 * Payload variable families map onto two Matter anchors each, so one rule serves light and dark:
 * elevation 0 is the page background and 1000 the text colour; status scales run from the soft
 * tint (50) to the strong colour (950).
 */
export function buildMapping(): string {
  const lines: string[] = [
    "--theme-bg: var(--m-bg);",
    "--theme-text: var(--m-text);",
    "--theme-input-bg: var(--m-surface);",
    "--theme-border-color: var(--m-border);",
    "--theme-overlay: var(--m-overlay);",
    "--accessibility-outline: 2px solid var(--m-focus);",
    "--font-body: var(--m-font-sans);",
    "--font-mono: var(--m-font-mono);",
    "--style-radius-s: var(--m-radius-sm);",
    "--style-radius-m: var(--m-control-radius);",
    "--style-radius-l: var(--m-radius-lg);",
  ];
  for (const n of steps(0, 1000, 50)) {
    lines.push(
      `--theme-elevation-${String(n)}: color-mix(in srgb, var(--m-text) ${String(n / 10)}%, var(--m-bg));`,
    );
  }
  for (const [family, token] of [
    ["success", "success"],
    ["warning", "warning"],
    ["error", "danger"],
  ] as const) {
    for (const n of steps(50, 950, 50)) {
      lines.push(
        `--theme-${family}-${String(n)}: color-mix(in srgb, var(--m-${token}) ${String(n / 10)}%, var(--m-${token}-soft));`,
      );
    }
  }
  return `@layer payload {\n  :root,\n  html[data-theme] {\n${lines.map((line) => `    ${line}`).join("\n")}\n  }\n}\n`;
}

export function buildPayloadCss(matterCss: string): string {
  return `/* Generated by @interstellarforge/matter-payload. Do not edit. */\n@layer payload-default, payload;\n${remapAttributes(matterCss)}${buildMapping()}`;
}
