import {
  type ColorMode,
  cssPrefix,
  defaultDensity,
  defaultTheme,
  type ThemeTokens,
  type TokenSet,
  type TokenValues,
} from "./tokens.ts";

const banner = `/* Generated by @interstellarforge/matter-tokens. Do not edit. */
@layer matter.reset, matter.tokens, matter.base, matter.components;
`;

function block(selectors: string[], values: TokenValues): string {
  const declarations = Object.entries(values).map(
    ([name, value]) => `    --${cssPrefix}-${name}: ${value};`,
  );
  return `  ${selectors.join(",\n  ")} {\n${declarations.join("\n")}\n  }`;
}

/**
 * Selector order matters: baseline, then OS preference, then explicit attribute.
 * A theme without a light mode uses its only mode as baseline.
 */
function themeBlocks(theme: ThemeTokens): string[] {
  const root = `:root[data-theme="${theme.name}"]`;
  const baselineSelectors =
    theme.name === defaultTheme ? [root, ":root:not([data-theme])"] : [root];
  const { light, dark } = theme.modes;
  const baseline = light ?? dark;
  if (baseline === undefined) {
    throw new Error(`Theme ${theme.name} has no colour modes`);
  }
  const blocks = [block(baselineSelectors, { ...theme.base, ...baseline })];
  if (light !== undefined && dark !== undefined) {
    const osSelectors = baselineSelectors.map(
      (selector) => `${selector}:not([data-color-mode="light"])`,
    );
    blocks.push(
      `  @media (prefers-color-scheme: dark) {\n${block(osSelectors, dark).replaceAll("\n", "\n  ").replace(/^/, "  ")}\n  }`,
    );
  }
  for (const mode of ["light", "dark"] satisfies ColorMode[]) {
    const values = theme.modes[mode];
    if (values !== undefined) {
      const selectors = baselineSelectors.map(
        (selector) => `${selector}[data-color-mode="${mode}"]`,
      );
      blocks.push(block(selectors, values));
    }
  }
  return blocks;
}

export function buildCss(set: TokenSet): string {
  const blocks = [
    block([":root"], set.core),
    ...Object.entries(set.densities).map(([name, values]) =>
      block(
        name === defaultDensity
          ? [":root", `[data-density="${name}"]`]
          : [`[data-density="${name}"]`],
        values,
      ),
    ),
    ...set.themes.flatMap(themeBlocks),
  ];
  return `${banner}@layer matter.tokens {\n${blocks.join("\n")}\n}\n`;
}
